import { z } from 'zod';

export const MEDICAL_SCHEMA_VERSION = '1.0' as const;
export const MAX_TRANSCRIPT_LENGTH = 100_000;

export const DateOnlySchema = z.string().regex(/^\d{4}-\d{2}-\d{2}$/, 'Date attendue au format AAAA-MM-JJ').refine((value) => {
  const date = new Date(`${value}T00:00:00.000Z`);
  return !Number.isNaN(date.getTime()) && date.toISOString().slice(0, 10) === value;
}, 'Date invalide');
const TimestampSchema = z.iso.datetime();
const ClinicalTextSchema = z.string().max(4_000).nullable();
const EyesSchema = z.strictObject({ od: ClinicalTextSchema, og: ClinicalTextSchema });

export const PatientSchema = z.strictObject({
  nom: z.string().trim().min(1, 'Le nom du patient est obligatoire').max(120),
  prenom: z.string().trim().max(120).nullable(),
  date_naissance: DateOnlySchema.nullable(),
});
export const ConsultationTypeSchema = z.enum(['assessment', 'follow_up', 'urgent']);
export const CONSULTATION_TYPE_LABELS: Record<z.infer<typeof ConsultationTypeSchema>, string> = {
  assessment: 'Bilan orthoptique',
  follow_up: 'Consultation de suivi',
  urgent: 'Urgence',
};
export const ConsultationStatusSchema = z.enum(['draft', 'in_progress', 'completed']);

// Text extraction contract: absence is null; clinical units/ranges require professional review.
// Patient identity and server metadata cannot be generated by the AI provider.
export const MedicalReportSchema = z.strictObject({
  contexte: z.strictObject({
    motif_demande: ClinicalTextSchema,
    suivi_ophtalmologique: ClinicalTextSchema,
    correction_visuelle: ClinicalTextSchema,
    signes_fonctionnels: ClinicalTextSchema,
  }),
  bilan_sensoriel: z.strictObject({
    acuite_visuelle: z.strictObject({ vision_lointaine: EyesSchema, vision_proche: EyesSchema, correction: ClinicalTextSchema }),
    capacites_fusionnelles: z.strictObject({ convergence: ClinicalTextSchema, divergence: ClinicalTextSchema, convergence_proche: ClinicalTextSchema, divergence_proche: ClinicalTextSchema, valeur_brute: ClinicalTextSchema }),
    acuite_stereoscopique: ClinicalTextSchema,
    conclusion: ClinicalTextSchema,
  }),
  bilan_optomoteur: z.strictObject({
    parallellisme: z.strictObject({ pres: ClinicalTextSchema, loin: ClinicalTextSchema }),
    mesure_angle_prismes: z.strictObject({ vision_proche: ClinicalTextSchema, vision_lointaine: ClinicalTextSchema, valeur_brute: ClinicalTextSchema }),
    motilite: ClinicalTextSchema,
    motricite_conjuguee: z.strictObject({ fixation: ClinicalTextSchema, poursuite: ClinicalTextSchema, saccades: ClinicalTextSchema }),
    ppc: ClinicalTextSchema,
    conclusion: ClinicalTextSchema,
  }),
  conclusion: z.strictObject({ synthese_clinique: ClinicalTextSchema, prise_en_charge: ClinicalTextSchema, recommandations: ClinicalTextSchema, suivi: ClinicalTextSchema }),
});
export type MedicalReport = z.infer<typeof MedicalReportSchema>;

export function createEmptyMedicalReport(): MedicalReport {
  return {
    contexte: { motif_demande: null, suivi_ophtalmologique: null, correction_visuelle: null, signes_fonctionnels: null },
    bilan_sensoriel: {
      acuite_visuelle: { vision_lointaine: { od: null, og: null }, vision_proche: { od: null, og: null }, correction: null },
      capacites_fusionnelles: { convergence: null, divergence: null, convergence_proche: null, divergence_proche: null, valeur_brute: null },
      acuite_stereoscopique: null, conclusion: null,
    },
    bilan_optomoteur: {
      parallellisme: { pres: null, loin: null },
      mesure_angle_prismes: { vision_proche: null, vision_lointaine: null, valeur_brute: null },
      motilite: null, motricite_conjuguee: { fixation: null, poursuite: null, saccades: null }, ppc: null, conclusion: null,
    },
    conclusion: { synthese_clinique: null, prise_en_charge: null, recommandations: null, suivi: null },
  };
}
export const medicalReportJsonSchema = z.toJSONSchema(MedicalReportSchema, { target: 'draft-2020-12' });

export const ReportProposalSchema = z.strictObject({
  schemaVersion: z.literal(MEDICAL_SCHEMA_VERSION),
  data: MedicalReportSchema,
  sourceTranscript: z.string().max(MAX_TRANSCRIPT_LENGTH),
  sourceRevision: z.number().int().positive(),
  generatedAt: TimestampSchema,
  provider: z.string().min(1).max(100),
  model: z.string().min(1).max(200),
});
export const ValidatedReportSchema = ReportProposalSchema.extend({ reviewedAt: TimestampSchema });
export const ConsultationSchema = z.strictObject({
  id: z.uuid(),
  patient: PatientSchema,
  consultationDate: DateOnlySchema,
  consultationType: ConsultationTypeSchema,
  notes: z.string().max(10_000),
  transcript: z.string().max(MAX_TRANSCRIPT_LENGTH),
  status: ConsultationStatusSchema,
  revision: z.number().int().positive(),
  createdAt: TimestampSchema,
  updatedAt: TimestampSchema,
  reportProposal: ReportProposalSchema.nullable(),
  validatedReport: ValidatedReportSchema.nullable(),
});
export const ConsultationSummarySchema = ConsultationSchema.pick({ id: true, patient: true, consultationDate: true, consultationType: true, status: true, revision: true, updatedAt: true });
export const ConsultationListSchema = z.array(ConsultationSummarySchema);
export const CreateConsultationInputSchema = ConsultationSchema.pick({ patient: true, consultationDate: true, consultationType: true }).extend({
  notes: z.string().max(10_000).default(''),
  transcript: z.string().max(MAX_TRANSCRIPT_LENGTH).default(''),
}).refine((value) => value.patient.date_naissance === null || value.patient.date_naissance <= value.consultationDate, { message: 'La naissance doit précéder la consultation', path: ['patient', 'date_naissance'] });
export const RevisionSchema = z.strictObject({ expectedRevision: z.number().int().positive() });
export const UpdateConsultationInputSchema = RevisionSchema.extend({
  patient: PatientSchema.optional(),
  consultationDate: DateOnlySchema.optional(),
  consultationType: ConsultationTypeSchema.optional(),
  notes: z.string().max(10_000).optional(),
}).refine((value) => Object.keys(value).some((key) => key !== 'expectedRevision'), 'Aucune modification fournie');
export const SaveTranscriptInputSchema = RevisionSchema.extend({ transcript: z.string().max(MAX_TRANSCRIPT_LENGTH) });
export const StructureTranscriptInputSchema = RevisionSchema;
export const ReviewInputSchema = RevisionSchema.extend({ data: MedicalReportSchema });
export const LoginSchema = z.strictObject({ username: z.string().trim().min(1).max(120), password: z.string().min(1).max(1_024) });
export const UserSchema = z.strictObject({ id: z.uuid(), username: z.string().min(1).max(120) });
export const SessionSchema = z.strictObject({ user: UserSchema });
export const ErrorResponseSchema = z.strictObject({ error: z.strictObject({ code: z.string(), message: z.string(), details: z.unknown().optional() }) });

export type Patient = z.infer<typeof PatientSchema>;
export type ConsultationType = z.infer<typeof ConsultationTypeSchema>;
export type ConsultationStatus = z.infer<typeof ConsultationStatusSchema>;
export type Consultation = z.infer<typeof ConsultationSchema>;
export type ConsultationSummary = z.infer<typeof ConsultationSummarySchema>;
export type ReportProposal = z.infer<typeof ReportProposalSchema>;
export type ValidatedReport = z.infer<typeof ValidatedReportSchema>;
export type CreateConsultationInput = z.input<typeof CreateConsultationInputSchema>;
export type CreateConsultationData = z.output<typeof CreateConsultationInputSchema>;
export type UpdateConsultationInput = z.infer<typeof UpdateConsultationInputSchema>;
export type SaveTranscriptInput = z.infer<typeof SaveTranscriptInputSchema>;
export type StructureTranscriptInput = z.infer<typeof StructureTranscriptInputSchema>;
export type ReviewInput = z.infer<typeof ReviewInputSchema>;
export type User = z.infer<typeof UserSchema>;
export type Session = z.infer<typeof SessionSchema>;
export type LoginInput = z.infer<typeof LoginSchema>;
export type ErrorResponse = z.infer<typeof ErrorResponseSchema>;

export const CreateConsultationSchema = CreateConsultationInputSchema;
export const UpdateConsultationSchema = UpdateConsultationInputSchema;
export const SaveTranscriptSchema = SaveTranscriptInputSchema;
export const StructureTranscriptSchema = StructureTranscriptInputSchema;
export const ReviewReportSchema = ReviewInputSchema;
export function patientDisplayName(patient: Patient): string { return [patient.prenom, patient.nom].filter(Boolean).join(' '); }
